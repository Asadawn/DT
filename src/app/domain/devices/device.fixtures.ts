export function connectivityBreakdown(devices: Device[]): Record<DeviceConnectivityStatus, number> {
  const breakdown: Record<DeviceConnectivityStatus, number> = {
    online: 0,
    offline: 0,
    stale: 0,
    warning: 0,
    error: 0,
    disabled: 0,
    unknown: 0,
  };
  for (const device of devices) {
    breakdown[device.connectivity]++;
  }
  return breakdown;
}
