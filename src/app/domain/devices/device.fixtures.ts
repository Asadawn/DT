const NOW = Date.now();
const minutesAgo = (m: number) => new Date(NOW - m * 60_000).toISOString();

function prop(
  id: string,
  key: string,
  label: string,
  value: DeviceProperty['value'],
  unit: string | undefined,
  valueType: DeviceProperty['valueType'],
  writable: boolean,
  updatedMinutesAgo: number,
  min?: number,
  max?: number,
): DeviceProperty {
  return {
    id,
    key,
    label,
    value,
    unit,
    valueType,
    writable,
    updatedAt: minutesAgo(updatedMinutesAgo),
    quality: 'good',
    min,
    max,
  };
}

